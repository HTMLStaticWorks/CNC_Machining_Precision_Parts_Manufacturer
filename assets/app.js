function applyTranslations(lang) {
  const dict = i18n[lang] || i18n['en'];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (dict[key].includes('<')) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });
}

function bindRTL(){
  const buttons = document.querySelectorAll('.rtl-toggle');
  const saved = localStorage.getItem('forgea-rtl');
  const isRtl = saved === 'rtl';

  const setRTLState = (active) => {
    document.documentElement.dir = active ? 'rtl' : 'ltr';
    document.body.classList.toggle('rtl', active);
    buttons.forEach(b => {
      b.classList.toggle('active', active);
      b.setAttribute('aria-pressed', active ? 'true' : 'false');
    });
  };

  if (isRtl) setRTLState(true);

  buttons.forEach(b => {
    b.addEventListener('click', () => {
      const activeNow = document.documentElement.dir === 'rtl' || document.body.classList.contains('rtl');
      const nextActive = !activeNow;
      localStorage.setItem('forgea-rtl', nextActive ? 'rtl' : 'ltr');
      setRTLState(nextActive);
    });
  });
}

function bindTheme(){
  const buttons=document.querySelectorAll('.theme-toggle');
  const saved=localStorage.getItem('forgea-theme'); if(saved==='light') document.body.classList.add('light');
  const update=()=>buttons.forEach(b=>b.textContent=document.body.classList.contains('light')?'☀':'☾'); update();
  buttons.forEach(b=>b.addEventListener('click',()=>{document.body.classList.toggle('light');localStorage.setItem('forgea-theme',document.body.classList.contains('light')?'light':'dark');update()}));
}

bindTheme();
bindRTL();

document.addEventListener('click', (e) => {
  const faqBtn = e.target.closest('.faq-question');
  if (faqBtn) {
    const item = faqBtn.closest('.faq-item');
    if (item) {
      item.classList.toggle('open');
    }
    return;
  }

  const dropBtn = e.target.closest('.dropbtn');
  if (dropBtn && window.innerWidth <= 992) {
    e.preventDefault();
    const dropdown = dropBtn.closest('.dropdown');
    if (dropdown) {
      dropdown.classList.toggle('open');
    }
    return;
  }

  const toggleBtn = e.target.closest('.menu-toggle');
  if (toggleBtn) {
    const navlinks = document.querySelector('.navlinks');
    if (navlinks) {
      navlinks.classList.toggle('open');
      toggleBtn.setAttribute('aria-expanded', navlinks.classList.contains('open'));
    }
    return;
  }
  
  const openNav = document.querySelector('.navlinks.open');
  if (openNav && !e.target.closest('.navlinks') && !e.target.closest('.menu-toggle')) {
    openNav.classList.remove('open');
  }
});

